#!/usr/bin/env sh
# First-run setup for the Compose quick start. Safe to run again: it never overwrites what exists
# (pass --force to start over).
#
#   ./init.sh && docker compose up -d --build
#
# It writes .env with random secrets, and dex/config.yaml with bcrypt hashes of two random demo
# passwords. Nothing here is a default credential: every value is generated on your machine.
set -eu
cd "$(dirname "$0")"

force=0
[ "${1:-}" = "--force" ] && force=1

rand() { # rand <hex-chars>
  od -An -N"$(( $1 / 2 ))" -tx1 /dev/urandom | tr -d ' \n'
}
pass() { # 24 characters without look-alikes
  LC_ALL=C tr -dc 'abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789' </dev/urandom | head -c 24
}
bcrypt() { # bcrypt <password>: the hash Dex expects ($2a$). htpasswd runs in a throwaway container.
  # shellcheck disable=SC2016  # the sed expression is meant literally
  docker run --rm httpd:2.4-alpine htpasswd -nbBC 10 "" "$1" | tr -d ':\n' | sed 's/^\$2y\$/$2a$/'
}

if [ -f .env ] && [ "$force" = 0 ]; then
  echo ".env already exists, keeping it (use --force to regenerate)."
else
  cat > .env <<ENV
# Generated by init.sh. Never commit this file.
RAMPART_OWNER_PASSWORD=$(rand 32)
RAMPART_APP_PASSWORD=$(rand 32)
RAMPART_SYSTEM_PASSWORD=$(rand 32)
S3_ACCESS_KEY=$(rand 20)
S3_SECRET_KEY=$(rand 40)
RAMPART_OIDC_CLIENT_SECRET=$(rand 48)
# Exactly 32 characters: signs CSRF tokens and seals the login state.
RAMPART_SESSION_KEY=$(rand 32)
# The first administrator, created inside Rampart at first start (username: admin).
RAMPART_ADMIN_PASSWORD=$(pass)
# Demo users in Dex (ada is bound to the admin role, grace is a viewer).
DEMO_ADMIN_PASSWORD=$(pass)
DEMO_VIEWER_PASSWORD=$(pass)
ENV
  chmod 600 .env
  echo "Wrote .env"
fi

if [ -f dex/config.yaml ] && [ "$force" = 0 ]; then
  echo "dex/config.yaml already exists, keeping it."
else
  # shellcheck disable=SC1091
  . ./.env
  admin_hash=$(bcrypt "$DEMO_ADMIN_PASSWORD")
  viewer_hash=$(bcrypt "$DEMO_VIEWER_PASSWORD")
  sed -e "s|@DEMO_ADMIN_HASH@|$admin_hash|" -e "s|@DEMO_VIEWER_HASH@|$viewer_hash|" dex/config.yaml.tpl > dex/config.yaml
  chmod 600 dex/config.yaml
  echo "Wrote dex/config.yaml"
fi

# shellcheck disable=SC1091
. ./.env
cat <<MSG

Ready. Start it with:  docker compose up -d --build
Then open http://localhost:8080

  Single sign-on (Dex)   ada@example.com    $DEMO_ADMIN_PASSWORD     (admin)
                         grace@example.com  $DEMO_VIEWER_PASSWORD     (viewer)
  Local administrator    admin              $RAMPART_ADMIN_PASSWORD  (the first admin, for setup and emergencies)

These are also in .env. Rotate the local administrator's password with:
  docker compose exec -T rampart /app/rampart admin set-password < new-password.txt
MSG
