#!/usr/bin/env python3
"""Writes deploy/rampart-crds.yaml: every CustomResourceDefinition of deploy/crds in one multi-document file, so the CRDs can be
installed or updated with one link:

    kubectl apply --server-side -f https://raw.githubusercontent.com/taha2samy-3/Rampart/main/deploy/rampart-crds.yaml

deploy/crds is the source (one file per kind), and the Helm chart carries an identical copy (CI diffs the two). Helm installs the
chart's crds/ folder on the first install only and never updates it on an upgrade, so this file is how the CRDs of a newer
release get to a cluster that already has Rampart. `--check` writes nothing and fails if the file is out of date.
Usage: hack/crds-bundle.py [--check]"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "deploy/crds"
OUT = ROOT / "deploy/rampart-crds.yaml"

HEAD = """# GENERATED by hack/crds-bundle.py from deploy/crds/*.yaml. Do not edit: edit the file in deploy/crds and run the script.
# Every CustomResourceDefinition of Rampart, one document each:
#   kubectl apply --server-side -f https://raw.githubusercontent.com/taha2samy-3/Rampart/main/deploy/rampart-crds.yaml
"""


def build():
    docs = []
    for p in sorted(SRC.glob("*.yaml")):
        text = p.read_text().strip("\n")
        if "kind: CustomResourceDefinition" not in text:
            sys.exit(f"crds-bundle.py: {p.name} is not a CustomResourceDefinition")
        docs.append(f"# deploy/crds/{p.name}\n{text}")
    return HEAD + "---\n" + "\n---\n".join(docs) + "\n"


want = build()
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != want:
        sys.exit("crds-bundle.py: deploy/rampart-crds.yaml is out of date: run hack/crds-bundle.py")
    print(f"checked {want.count('kind: CustomResourceDefinition')} CRDs")
else:
    OUT.write_text(want)
    print(f"wrote {OUT.relative_to(ROOT)}: {want.count('kind: CustomResourceDefinition')} CRDs")
